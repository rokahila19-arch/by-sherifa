-- 1) Gérantes autorisées à modifier le catalogue (par e-mail de connexion)
create table if not exists public.admins (
  email text primary key
);
alter table public.admins enable row level security;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.admins where email = auth.jwt() ->> 'email');
$$;

drop policy if exists "admins lisent la liste" on public.admins;
create policy "admins lisent la liste" on public.admins for select using (public.is_admin());

-- 2) Articles
create table if not exists public.products (
  id          bigint generated by default as identity primary key,
  title       text        not null,
  category    text        not null,
  brand       text,
  images      text[]      not null default '{}',
  price       integer     not null check (price >= 0),
  old_price   integer     check (old_price >= 0),
  rating      numeric(2,1) not null default 5,
  reviews     integer     not null default 0,
  sold        integer     not null default 0,
  stock       integer     not null default 0,
  min_order   integer     not null default 1,
  wholesale   jsonb       not null default '[]',
  colors      jsonb,
  sizes       text[],
  description text        not null default '',
  flash       boolean     not null default false,
  is_new      boolean     not null default true,
  active      boolean     not null default true,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create index if not exists products_category_idx on public.products (category);

create or replace function public.touch_updated_at()
returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end;
$$;
drop trigger if exists products_touch on public.products;
create trigger products_touch before update on public.products
  for each row execute function public.touch_updated_at();

alter table public.products enable row level security;

-- Tout le monde voit les articles en ligne ; les gérantes voient aussi les articles masqués.
drop policy if exists "lecture publique" on public.products;
create policy "lecture publique" on public.products for select using (active or public.is_admin());

drop policy if exists "gerantes ajoutent" on public.products;
create policy "gerantes ajoutent" on public.products for insert with check (public.is_admin());

drop policy if exists "gerantes modifient" on public.products;
create policy "gerantes modifient" on public.products for update using (public.is_admin()) with check (public.is_admin());

drop policy if exists "gerantes suppriment" on public.products;
create policy "gerantes suppriment" on public.products for delete using (public.is_admin());

-- 3) Photos des articles (stockage public en lecture)
insert into storage.buckets (id, name, public)
values ('product-images', 'product-images', true)
on conflict (id) do update set public = true;

drop policy if exists "photos lecture publique" on storage.objects;
create policy "photos lecture publique" on storage.objects for select
  using (bucket_id = 'product-images');

drop policy if exists "photos ajout gerantes" on storage.objects;
create policy "photos ajout gerantes" on storage.objects for insert
  with check (bucket_id = 'product-images' and public.is_admin());

drop policy if exists "photos modif gerantes" on storage.objects;
create policy "photos modif gerantes" on storage.objects for update
  using (bucket_id = 'product-images' and public.is_admin());

drop policy if exists "photos suppression gerantes" on storage.objects;
create policy "photos suppression gerantes" on storage.objects for delete
  using (bucket_id = 'product-images' and public.is_admin());
